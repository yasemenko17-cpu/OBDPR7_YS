-- Набір 3: Фітнес-клуб. Схему й дані створює тест у тимчасовій схемі; не редагуйте файл.
CREATE TABLE hall (
    id          integer PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    location    text
);
CREATE TABLE workout (
    id          integer PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    title       text NOT NULL,
    hall_id     integer REFERENCES hall (id),
    price       numeric(8,2) NOT NULL CHECK (price > 0),
    seats       integer NOT NULL CHECK (seats >= 0),
    status      text NOT NULL CHECK (status IN ('active', 'draft', 'archived')),
    starts_on   date NOT NULL
);
CREATE TABLE member (
    id          integer PRIMARY KEY,
    full_name   text NOT NULL,
    email       text,
    city        text,
    joined_on   date NOT NULL,
    referred_by integer REFERENCES member (id)
);
CREATE TABLE booking (
    id          integer PRIMARY KEY,
    member_id   integer NOT NULL REFERENCES member (id),
    workout_id  integer NOT NULL REFERENCES workout (id),
    places      integer NOT NULL CHECK (places > 0),
    booked_on   date NOT NULL,
    cancelled_on date,
    CHECK (cancelled_on IS NULL OR cancelled_on >= booked_on)
);

