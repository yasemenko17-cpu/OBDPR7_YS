-- Набір 1: Бібліотека. Схему й дані створює тест у тимчасовій схемі; не редагуйте файл.
CREATE TABLE publisher (
    id          integer PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    city        text
);
CREATE TABLE book (
    id          integer PRIMARY KEY,
    isbn        text NOT NULL UNIQUE,
    title       text NOT NULL,
    publisher_id integer REFERENCES publisher (id),
    price       numeric(8,2) NOT NULL CHECK (price > 0),
    copies      integer NOT NULL CHECK (copies >= 0),
    status      text NOT NULL CHECK (status IN ('active', 'draft', 'archived')),
    published_on date NOT NULL
);
CREATE TABLE reader (
    id          integer PRIMARY KEY,
    full_name   text NOT NULL,
    email       text,
    city        text,
    joined_on   date NOT NULL,
    referred_by integer REFERENCES reader (id)
);
CREATE TABLE loan (
    id          integer PRIMARY KEY,
    reader_id   integer NOT NULL REFERENCES reader (id),
    book_id     integer NOT NULL REFERENCES book (id),
    copies      integer NOT NULL CHECK (copies > 0),
    loaned_on   date NOT NULL,
    returned_on date,
    CHECK (returned_on IS NULL OR returned_on >= loaned_on)
);

